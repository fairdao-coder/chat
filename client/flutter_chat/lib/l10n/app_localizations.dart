  static AppLocalizations _resolve(Locale locale) {
    if (locale.countryCode == 'TW') return const AppLocalizations(_zhHant);
    if (locale.languageCode == 'en') return const AppLocalizations(_en);
    if (locale.languageCode == 'es') return const AppLocalizations(_es);
    return const AppLocalizations(_zhHans);
  }

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations)!;

  /// 供 MaterialApp.localizationsDelegates 使用。
  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();
}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => L10n.supportedLocales.any((s) =>
      s.languageCode == locale.languageCode &&
      (s.countryCode == null || s.countryCode == locale.countryCode));

  @override
  Future<AppLocalizations> load(Locale locale) async => L10n._resolve(locale);

  @override
  bool shouldReload(covariant _AppLocalizationsDelegate old) => false;
}

/// 便捷訪問：`context.tr('设置')`。
extension L10nContext on BuildContext {
  String tr(String key) => L10n.of(this).t(key);
}
